"""The labelled benchmark: natural-language questions with hand-written gold SQL.

150 questions in three sets:
  * SALES    (90) over the real 50,000-row `sales` table — the domain the
             rule-based parser was built for.
  * HINGLISH (15) the same table, asked in Hindi written in English letters.
  * MULTI    (45) over four uploaded tables (customers, products, orders,
             orders_archive) — joins, merges and aggregation across files.

Conventions, so each question has exactly one right answer:
  * "sales records / transactions / orders" asks for a row COUNT;
    "units / quantity sold" asks for SUM(quantity_sold)  (sales table).
  * "revenue" is price x quantity.
  * Questions that return a list say which fields they want.
  * Dates in `sales` are ISO text; "dispatched" means dispatch_date.
Gold queries never end in a tie at a LIMIT boundary (checked by validate.py).
"""


